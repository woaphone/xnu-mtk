/*
 * Linux port: the DriverKit user-server implementation (IOUserServer.cpp) is
 * built from IIG-generated interfaces, and IIG ships only with Xcode. This
 * kernel is a first-boot console that does not launch DriverKit extensions, so
 * the server is excluded from iokit/conf/files and the entry points that core
 * IOKit calls are answered here without starting a server.
 *
 * The dispatch methods are normally generated into the IIG *.iig.cpp files;
 * here they refuse every IORPC. No DriverKit extension exists to send one.
 */
