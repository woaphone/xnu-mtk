/*
 * The state-notification service is created during IOService::initialize().
 * The DriverKit version tracks per-service sleep reasons; a plain IOService is
 * enough for a first-boot console (no DriverKit extensions subscribe).
 */
IOService *
IOSystemStateNotification::initialize(void)
{
	IOService * service = OSTypeAlloc(IOService);
	if (service && !service->init()) {
		service->release();
		return NULL;
	}
	return service;
}

